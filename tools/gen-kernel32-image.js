#!/usr/bin/env node
'use strict';
// The checked-in manifest is an explicit native export surface. Do not infer
// DLL ownership from the process-wide API hash table.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const manifest = require('../src/kernel32-exports.json');
const apis = require('../src/api_table.json');
const seen = new Set();
const entries = [...manifest.exports].sort((a, b) => {
  if (!a.name) return b.name ? 1 : a.ordinal - b.ordinal;
  if (!b.name) return -1;
  return Buffer.compare(Buffer.from(a.name, 'ascii'), Buffer.from(b.name, 'ascii'));
});
const named = entries.filter(e => e.name);
if (entries.length * 8 > 4096 || named.length * 4 > 2048 || named.length * 2 > 2048 ||
    entries.reduce((n, e) => n + ((Buffer.byteLength(e.api) + 6) & ~3), 32768) > 65536)
  throw new Error('KERNEL32 PE export regions overflow');
if (new Set(named.map(e => e.name)).size !== named.length) throw new Error('Duplicate export name');
let namedIndex = 0;
const lines = [';; Generated by tools/gen-kernel32-image.js; explicit KERNEL32 exports.',
  '(func $kernel32_populate_exports (param $base i32)',
  '  (local $cursor i32)', '  (local.set $cursor (i32.const 32768))'];
for (const [index, item] of entries.entries()) {
  if (seen.has(item.ordinal) || !Number.isInteger(item.ordinal) || item.ordinal < 1 || item.ordinal > 1024)
    throw new Error('Invalid/duplicate ordinal');
  seen.add(item.ordinal);
  if (!apis.some(a => a.name === item.api) || !/^[A-Za-z0-9_]+$/.test(item.api)) throw new Error('Unknown API');
  if (item.name && item.name !== item.api) throw new Error('Named API alias needs explicit implementation');
  // The production WATX string pool is intentionally small. Names belong in
  // this guest image, not in a second permanent emulator-private string copy.
  const bytes = Buffer.alloc((item.api.length + 6) & ~3);
  bytes.write(item.api, 2, 'ascii'); // IMAGE_IMPORT_BY_NAME hint followed by name
  lines.push(`  ;; ${item.api}`);
  for (let offset = 0; offset < bytes.length; offset += 4)
    lines.push(`  (call $gs32 (i32.add (local.get $base) (i32.add (local.get $cursor) (i32.const ${offset}))) (i32.const ${bytes.readUInt32LE(offset)}))`);
  lines.push(`  (local.set $cursor (call $kernel32_emit_export (local.get $base) (i32.const ${index}) (i32.const ${item.ordinal}) (i32.const ${apis.find(a => a.name === item.api).id}) (i32.const ${item.name ? namedIndex++ : -1}) (i32.const ${bytes.length}) (local.get $cursor)))`);
}
lines.push(`  (call $gs32 (i32.add (local.get $base) (i32.const 16408)) (i32.const ${manifest.exports.filter(e => e.name).length}))`, ')', '');
const out = path.join(root, 'src/08-pe-loader.wat');
const source = fs.readFileSync(out, 'utf8');
const begin = ';; BEGIN GENERATED KERNEL32 EXPORTS\n';
const end = ';; END GENERATED KERNEL32 EXPORTS';
if (source.split(begin).length !== 2 || source.split(end).length !== 2)
  throw new Error('KERNEL32 generated section needs unique boundary markers');
const start = source.indexOf(begin) + begin.length, stop = source.indexOf(end);
if (stop < start) throw new Error('Reversed KERNEL32 generated section markers');
const generated = lines.join('\n');
if (process.argv.includes('--check')) {
  if (source.slice(start, stop) !== generated) throw new Error('Stale KERNEL32 exports');
} else fs.writeFileSync(out, source.slice(0, start) + generated + source.slice(stop));
