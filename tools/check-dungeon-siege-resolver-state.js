'use strict';
const assert = require('node:assert/strict'), crypto = require('node:crypto');
const { captureResolverState } = require('./dungeon-siege-resolver-state');
const memory = { buffer: new ArrayBuffer(8 * 1024 ** 2) }, dv = new DataView(memory.buffer), bytes = new Uint8Array(memory.buffer);
const layout = { GUEST_BASE: 0x12000, BASE: { GUEST_PAGE_TABLE: 0x400000, DIB_BACKING_BASE: 0, VIRTUAL_MAP_STATE: 0x300000, VIRTUAL_RESERVE_TABLE: 0x301000 }, SIZE: { GUEST_PAGE_TABLE: 0x400000, VIRTUAL_RESERVE_TABLE: 0x10000 } };
const regs = { eip: 0x4178eb, image_base: 0x400000, esi: 0x410000, edi: 0x411000, ebx: 0x411018, fs_base: 0x412000, esp: 0x413000, ebp: 0x413010, eax: 7, ecx: 8, edx: 9 };
const e = Object.fromEntries(Object.entries(regs).map(([n, v]) => ['get_' + n, () => v]));
e.guest_to_wasm = () => { throw Error('Mutation forbidden'); };
const w = a => a - 0x400000 + 0x12000, put = (a, v) => dv.setUint32(w(a), v, true);
put(regs.esi, 0x414000); put(regs.esi + 12, regs.edi); put(regs.esi + 16, regs.ebx); put(regs.esi + 24, 0x76000000);
bytes.set(Buffer.from('kernel32.dll\0'), w(0x414000));
put(regs.edi, 0x415000); put(regs.edi + 4, 0x9000000); put(regs.edi + 12, 0x415004); put(regs.edi + 16, 42);
put(regs.fs_base, 0x416000); put(0x416000, 0x416000); put(0x416004, 0x409ef0); put(0x416008, 0x417000); put(0x41600c, 0);
put(0x417000, 0); put(0x417004, 0x418000); put(0x417008, 0x419000);
dv.setUint32(layout.BASE.VIRTUAL_MAP_STATE + 16, 1, true); dv.setUint32(layout.BASE.VIRTUAL_RESERVE_TABLE, 0x9000001, true); dv.setUint32(layout.BASE.VIRTUAL_RESERVE_TABLE + 4, 4096, true);
const hash = () => crypto.createHash('sha256').update(bytes).digest('hex'), before = hash();
const r = captureResolverState(e, memory, layout);
assert.equal(hash(), before); assert.equal(r.records[0].symbol.status, 'unmapped'); assert.equal(r.records[1].symbol.ordinal, 42);
assert.equal(r.holes[0].pte, 0); assert.equal(r.reservations[0].base, 0x9000000);
assert(r.issues.some(i => i.kind === 'fs-cycle')); assert(r.issues.some(i => i.kind === 'scope-invalid-or-cycle'));
dv.setUint32(layout.BASE.GUEST_PAGE_TABLE + (0x9000000 >>> 12) * 4, 0x200800, true);
bytes.set(Buffer.from('GetProcAddress\0'), 0x200000);
const mappedBefore = hash(), mapped = captureResolverState(e, memory, layout);
assert.equal(Buffer.from(mapped.records[0].symbol.bytes).toString(), 'GetProcAddress');
assert.equal(mapped.records[0].symbol.status, 'terminated'); assert.equal(hash(), mappedBefore);
bytes.fill(65, 0x200000, 0x200080);
assert.equal(captureResolverState(e, memory, layout).records[0].symbol.status, 'truncated-128');
const capped = captureResolverState({ ...e, get_ebx: () => regs.edi + 65 * 12 }, memory, layout);
assert.equal(capped.records.length, 64); assert(capped.issues.some(i => i.kind === 'records-truncated'));
assert(Buffer.byteLength(JSON.stringify(capped)) < 3 * 1024 ** 2);
assert.throws(() => captureResolverState({ ...e, get_eip: () => 0 }, memory, layout), /Wrong resolver/);
const bad = captureResolverState({ ...e, get_ebx: () => regs.edi - 1 }, memory, layout);
assert(bad.issues.some(i => i.kind === 'invalid-record-endpoints'));
dv.setUint32(layout.BASE.VIRTUAL_MAP_STATE + 16, 0xffffffff, true);
assert(captureResolverState(e, memory, layout).issues.some(i => i.kind === 'invalid-reservation-count'));
console.log('PASS: resolver read-only state, missing symbol/PTE/reservation, ordinals, cycles, invalid endpoints/count and wrong-EIP refusal.');
