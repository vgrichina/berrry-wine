#!/usr/bin/env node
'use strict';
// Independent, read-only runtime verification and compact evidence recovery.
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const crypto=require('node:crypto'),assert=require('node:assert/strict');
const [root,base,original]=process.argv.slice(2);
assert(root && base && original,'usage: ROOT OBSERVATION_BASE ORIGINAL_PAYLOAD');
const out=path.join(base,'licence-run');
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const read=p=>JSON.parse(fs.readFileSync(p));
const save=(p,v)=>fs.writeFileSync(p,JSON.stringify(v,null,2)+'\n');
const verify=(dir,files)=>{for(const f of files){assert.equal(sha(path.join(dir,f.path)),f.sha256,f.path);if(f.size!==undefined)assert.equal(fs.statSync(path.join(dir,f.path)).size,f.size,f.path);}};
const sources=read(path.join(out,'source-before.json'));
verify(root,sources);
const pins=read(path.join(base,'docs/re-notes/army-men-setup-compile-pins.json'));
verify(root,pins.files);assert.equal(sha(path.join(root,'build/wine-assembly.wasm')),pins.moduleSha256);
const payload=read(path.join(base,'docs/re-notes/army-men-setup-manifest.json'));
verify(original,[...payload.files,...payload.duplicates]);
const child=read(path.join(base,'docs/re-notes/army-men-child-manifest.json'));
verify(path.join(base,'run/capture'),[...child.files,...child.duplicates]);
assert.equal(sha(path.join(base,'run/registry.json')),child.registrySha256);
const active=cp.execFileSync('ps',['-eo','pid,comm'],{encoding:'utf8'}).split('\n').filter(s=>/node|MainThread|chrome|firefox|7z|curl/.test(s)&&Number(s.trim().split(/\s+/)[0])!==process.pid);
assert.deepEqual(active,[],'active runtime processes');
const walk=(dir,rel='')=>fs.readdirSync(path.join(dir,rel),{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(dir,path.join(rel,e.name)):[{path:path.join(rel,e.name),size:fs.statSync(path.join(dir,rel,e.name)).size,sha256:sha(path.join(dir,rel,e.name))}]);
const seal=walk(path.join(out,'final-vfs'));save(path.join(out,'final-vfs-seal.json'),seal);
const licencePaths=['armymen/license.txt','windows/temp/_istmp0.dir/license.txt'];
const retained=licencePaths.map(p=>{const f=seal.find(x=>x.path===p);assert(f,'missing licence file '+p);return {...f,source:'licence-run/final-vfs/'+p};});
assert.equal(retained[0].sha256,child.files.find(f=>f.path===licencePaths[0]).sha256,'original licence unchanged in final VFS');
save(path.join(out,'licence-files.json'),retained);
const post={at:new Date().toISOString(),sourceCount:sources.length,originalCount:payload.files.length,capturedCount:child.files.length,allSourceAndFixturesUnchanged:true,active,moduleSha256:pins.moduleSha256};
save(path.join(base,'licence-independent-postflight.json'),post);
const files=fs.readdirSync(out).filter(p=>fs.statSync(path.join(out,p)).isFile()).map(p=>'licence-run/'+p);
const archive=path.join(base,'licence-evidence.tar.gz');
cp.execFileSync('tar',['-czf',archive,'-C',base,...files,...retained.map(f=>f.source),'licence-independent-postflight.json','tools/army-men-licence-observe.js','tools/army-men-licence-postflight.js','docs/re-notes/army-men-child-manifest.json','docs/re-notes/army-men-setup-manifest.json','docs/re-notes/army-men-setup-compile-pins.json']);
console.log(JSON.stringify({...post,licences:retained,archive:{size:fs.statSync(archive).size,sha256:sha(archive)}}));
