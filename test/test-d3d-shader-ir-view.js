#!/usr/bin/env node
'use strict';
const assert = require('assert');
const IR = require('../lib/d3d-shader-ir');
const Shader = require('../lib/d3d9-shader');
const memory = new ArrayBuffer(512), v = new DataView(memory), p = 32;
const put = (at, values) => values.forEach((n, i) => v.setUint32(at + i * 4, n, true));
put(p, [IR.MAGIC, 1, 0, 0xfffe0101, 1, 5, 160, 0]);
put(p + 32, [1, 1, 2, 0]);
put(p + 48, [4, 0, 15, 0]);
put(p + 64, [1, 0, 0xe4, 0]);
const view = IR.read(memory, p);
const expected = Shader.compile(new Uint32Array([0xfffe0101, 1, 0xc00f0000, 0x90e40000, 0xffff]));
assert.strictEqual(Shader.compileIR(view).source, expected.source);
assert.strictEqual(Shader.compileNativeIR(view).source,expected.source);
assert.strictEqual(Shader.compileNativeIR({...view,instructions:[],version:0xffff0104}).source,expected.source,'serialized native IR is authoritative, not redundant JS projection');
assert.throws(()=>Shader.compileNativeIR(Shader.parse(new Uint32Array([0xfffe0101,0xffff]))),/native.*bytes/);
// ps_1_4 is a public profile (D3D9-PUBLIC-PS14); unknown IR flags still are not.
for(const [offset,value]of [[28,4]]){
 const bytes=view.nativeBytes.slice();new DataView(bytes.buffer).setUint32(offset,value,true);
 if(offset===12)new DataView(bytes.buffer).setUint32(8,1,true);
 assert.throws(()=>Shader.compileNativeIR({...view,nativeBytes:bytes}),/profile/);
}
assert(Object.isFrozen(view.instructions[0].args));
assert(view.nativeBytes instanceof Uint8Array);
assert.notStrictEqual(view.nativeBytes.buffer,memory,'native executor handoff owns bytes');
v.setUint32(p + 64 + 4, 3, true);
assert.strictEqual(view.instructions[0].args[1], 0x90e40000, 'view owns values after WAT allocation reuse');
assert.strictEqual(new DataView(view.nativeBytes.buffer).getUint32(68,true),0,'native IR input register survives allocation reuse');
assert.throws(() => IR.read(memory, 3), /bounds/);
v.setUint32(p + 24, 512, true);
assert.throws(() => IR.read(memory, p), /bounds/);
v.setUint32(p + 24, 160, true);
v.setUint32(p + 4, 2, true);
assert.throws(() => IR.read(memory, p), /ABI/);
assert.throws(() => Shader.compileIR({ ...view, version: 0xffff0300 }), /invalid/);
assert.throws(() => Shader.compileIR({ ...view, instructions: [{ opcode: 1234, args: [], offset: 1 }] }), /IR instruction/);
v.setUint32(p + 4, 1, true);
let compiles = 0, frees = 0;
const ex = { d3d_shader_ir_compile: () => { compiles++; return p; },
  d3d_shader_ir_free: pointer => { assert.strictEqual(pointer,p); frees++; } };
const cache = new IR.Compiler({getExports:()=>ex,getMemory:()=>memory,maxBytes:200,maxEntries:1});
put(256,[0xfffe0101,1,0xc00f0000,0x90e40000,0xffff]);
const first = cache.compile(256,5);
assert.strictEqual(cache.compile(256,5),first);
assert.strictEqual(compiles,1); assert.strictEqual(frees,1);
v.setUint32(268,0x90e40001,true);
assert.notStrictEqual(cache.compile(256,5),first,'reused pointer with changed bytes recompiles');
assert.strictEqual(compiles,2); assert.strictEqual(frees,2);
put(288,[0xfffe0101,1,0xc00f0000,0x90e40000,0xffff]);
cache.compile(288,5);
assert.strictEqual(cache.entries.size,1); assert(cache.bytes<=200);
cache.compile(256,5); assert.strictEqual(compiles,4,'evicted shader recompiles');
v.setUint32(p + 4,2,true); cache.clear();
assert.throws(()=>cache.compile(256,5),/ABI/);
assert.strictEqual(frees,5,'native allocation is freed even when projection fails');
assert.strictEqual(cache.bytes,0);
assert.throws(()=>cache.compile(511,5),/bounds/);
assert.throws(()=>new IR.Compiler({getExports:()=>({}),getMemory:()=>memory}).compile(256,5),/validator unavailable/);
v.setUint32(p+4,1,true);
const retainedCache=new IR.Compiler({getExports:()=>{throw Error('unexpected compiler access');},getMemory:()=>memory,maxBytes:200,maxEntries:1});
const retained=retainedCache.retained(p,5);assert.strictEqual(retainedCache.retained(p,5),retained);
assert.throws(()=>retainedCache.retained(p,6),/extent/);
v.setUint32(p+68,2,true);assert.notStrictEqual(retainedCache.retained(p,5),retained,'reused retained allocation invalidates cached projection');
assert(retainedCache.bytes<=200);assert.strictEqual(retainedCache.entries.size,1);
console.log('PASS WAT shader IR view: bounded ABI, immutable projection and GLSL parity');
