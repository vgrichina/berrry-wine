'use strict';
const assert = require('node:assert/strict');
const { NamedSyncNamespace } = require('../lib/named-sync-namespace');
const ns = new NamedSyncNamespace();
let wakes = 0;
const parent = { _wakeWaitersSoon() { wakes++; } };
const child = { _wakeWaitersSoon() { wakes++; } };
const event = ns.acquire(parent, 'Ion Game Mutex', 1, {}).object;
const opened = ns.acquire(child, 'Ion Game Mutex', 1,
  { initialState: true, manualReset: true });
assert.equal(opened.alreadyExists, true);
assert.equal(opened.object, event);
assert.equal(ns.wait(child, [event], false), 0x102, 'existing state ignores creation arguments');
assert.equal(ns.acquire(child, 'missing', 1, {}, true).error, 2);
assert.equal(ns.acquire(child, 'Ion Game Mutex', 3).error, 6, 'types share a namespace');
assert.equal(ns.acquire(child, 'ion game mutex', 1, {}, true).error, 2, 'case-sensitive names');
ns.setEvent(child, event, true);
assert.equal(wakes, 2, 'both process schedulers get a wake opportunity');
assert.equal(ns.wait(parent, [event], false), 0);
assert.equal(ns.wait(child, [event], false), 0x102, 'one signal releases only one waiter');
const other = ns.acquire(parent, 'second', 1, {}).object;
ns.setEvent(child, event, true);
assert.equal(ns.wait(parent, [event, other], true), 0x102);
assert.equal(ns.ready(child, event), true, 'failed wait-all leaves earlier event signaled');
ns.setEvent(parent, other, true);
assert.equal(ns.wait(parent, [event, other], true), 0);
assert.equal(ns.ready(child, event), false);
assert.equal(ns.ready(parent, other), false);
const manual = ns.acquire(parent, 'manual', 1, { manualReset: true }).object;
ns.acquire(child, 'manual', 1, {}, true);
ns.setEvent(parent, manual, true);
assert.equal(ns.wait(parent, [manual], false), 0);
assert.equal(ns.wait(child, [manual], false), 0);
ns.setEvent(child, manual, false);
assert.equal(ns.wait(parent, [manual], false), 0x102);
ns.acquire(parent, 'Ion Game Mutex', 1);
assert.equal(ns.close(parent, event), true);
assert.equal(ns.live(parent, event), true, 'intermediate close preserves reference');
assert.equal(ns.close(parent, event), true);
assert.equal(ns.live(parent, event), false);
assert.equal(ns.live(child, event), true, 'object outlives creating process handle');
assert.equal(ns.setEvent(parent, event, true), false, 'closed owner cannot signal');
ns.detach(child);
assert.equal(ns.objects.has('Ion Game Mutex'), false, 'last process exit removes name');
const replacement = ns.acquire(parent, 'Ion Game Mutex', 1).object;
assert.notEqual(replacement, event);
assert.equal(ns.live(parent, event), false, 'old object cannot alias a reused name');

const mutex = ns.acquire(parent, 'lock', 3, { initialOwner: true, threadId: 1 }).object;
ns.acquire(child, 'lock', 3);
assert.equal(ns.wait(child, [mutex], false, 1), 0x102,
  'same numeric thread id in another process is not the owner');
assert.equal(ns.releaseMutex(child, mutex, 1), 0);
assert.equal(ns.wait(parent, [mutex], false, 1), 0, 'recursive mutex acquisition');
assert.equal(ns.releaseMutex(parent, mutex, 1), 1);
assert.equal(ns.wait(child, [mutex], false, 1), 0x102, 'one recursion remains');
ns.detach(parent);
assert.equal(ns.wait(child, [mutex], false, 1), 0x80, 'owner exit abandons mutex');
assert.equal(ns.wait(child, [mutex], false, 1), 0, 'abandonment reported once');
ns.detach(child);
assert.equal(ns.objects.size, 0);
const vm = require('node:vm'), fs = require('node:fs');
const context = vm.createContext({ SharedArrayBuffer: undefined });
vm.runInContext(fs.readFileSync(require.resolve('../lib/named-sync-namespace'), 'utf8'), context);
const cooperative = new context.NamedSyncNamespace();
const e = cooperative.acquire(parent, 'without isolation', 1).object;
cooperative.acquire(child, 'without isolation', 1);
assert.equal(cooperative.shared, false);
cooperative.setEvent(parent, e, true);
assert.equal(cooperative.wait(child, [e], false), 0);
cooperative.detach(parent); cooperative.detach(child);
console.log('PASS shared namespace state, consumption, lifetime, wakeups and process-aware mutex ownership');
console.log('Integration pending: ThreadManager handles, mixed local waits, worker broker, browser lifecycle and CLI transport');
